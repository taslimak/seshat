"""Enumerations shared by the canonical dataset schema (schema_version 1.0.0)."""

from __future__ import annotations

from enum import StrEnum
from typing import Final, Literal

SCHEMA_VERSION: Final[Literal["1.0.0"]] = "1.0.0"


class SourceType(StrEnum):
    """Where a record came from. Only some sources can carry real usage labels."""

    CONTROLLED_EXPERIMENT = "controlled_experiment"
    CONSENTED_API_TELEMETRY = "consented_api_telemetry"
    AUTHORIZED_LOG_IMPORT = "authorized_log_import"
    PUBLIC_PERMITTED_DATASET = "public_permitted_dataset"
    SYNTHETIC_UNEXECUTED = "synthetic_unexecuted"
    TEST_FIXTURE = "test_fixture"


#: Sources whose observed usage comes from a real provider and may become a real label.
REAL_USAGE_SOURCES = frozenset(
    {
        SourceType.CONTROLLED_EXPERIMENT,
        SourceType.CONSENTED_API_TELEMETRY,
        SourceType.AUTHORIZED_LOG_IMPORT,
    }
)
#: Sources that never carry observed usage at all (prompts only).
UNLABELED_SOURCES = frozenset(
    {SourceType.PUBLIC_PERMITTED_DATASET, SourceType.SYNTHETIC_UNEXECUTED}
)


class ConsentStatus(StrEnum):
    NOT_REQUIRED = "not_required"  # project-authored or generated content, no end user
    GRANTED = "granted"  # explicit opt-in recorded for this content
    DENIED = "denied"
    UNKNOWN = "unknown"


class CollectionStatus(StrEnum):
    PLANNED = "planned"
    DRY_RUN = "dry_run"
    DISPATCHED = "dispatched"
    COMPLETED = "completed"
    FAILED = "failed"
    UNCERTAIN = "uncertain"  # dispatched, outcome unknown; never auto-retried
    IMPORTED = "imported"
    SKIPPED = "skipped"


class PreflightMethod(StrEnum):
    PROVIDER_NATIVE = "provider_native"
    LOCAL_TOKENIZER = "local_tokenizer"
    STATISTICAL_APPROXIMATION = "statistical_approximation"
    UNAVAILABLE = "unavailable"


class LabelQuality(StrEnum):
    VERIFIED = "verified"  # complete provider usage, accounting consistent
    PARTIAL = "partial"  # usable target present, some secondary fields unreported
    CENSORED = "censored"  # truncated output: true length unknown (right-censored)
    INCONSISTENT = "inconsistent"  # contradictory provider accounting; quarantined
    UNAVAILABLE = "unavailable"  # no usage observed (failed / uncertain / missing)
    SYNTHETIC = "synthetic"  # generated by a mock/test fixture; never a real label


class ResponseStatus(StrEnum):
    COMPLETED = "completed"
    INCOMPLETE = "incomplete"
    REFUSED = "refused"
    FAILED = "failed"
    UNCERTAIN = "uncertain"
    NOT_EXECUTED = "not_executed"


class CostMethod(StrEnum):
    PRICE_TABLE_ESTIMATE = "price_table_estimate"  # usage x versioned list prices
    PROVIDER_REPORTED = "provider_reported"  # cost returned by the provider
    UNAVAILABLE = "unavailable"


class ObservationKind(StrEnum):
    INVOCATION = "invocation"  # one billable API call (iterations already summed)
    WORKFLOW_AGGREGATE = "workflow_aggregate"  # derived roll-up; excluded from labels
