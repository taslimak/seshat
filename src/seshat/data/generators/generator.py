"""Reproducible experimental prompt generation.

``generate_prompts(count, seed)`` walks the template library in a balanced order
(template x length stratum), so categories and strata are evenly represented. Every
prompt records its template, seed, variation and measured length stratum. Prompts
generated from the same template and topic share a ``prompt_family_id`` so
near-identical variants never straddle train/test.
"""

from __future__ import annotations

import hashlib
import random
from dataclasses import dataclass

from seshat.data.generators.templates import (
    TEMPLATE_LIBRARY_VERSION,
    TEMPLATES,
    Stratum,
    sentence,
)
from seshat.data.models import PromptMessage, PromptRecord, ToolDefinition

GENERATOR_SOURCE = "template_generator"
NEAR_DUPLICATE_THRESHOLD = 0.8  # same default as configs/prompt_collection.json
TARGET_STRATA = (Stratum("short", 20, 60), Stratum("medium", 120, 450), Stratum("long", 700, 1800))


@dataclass(frozen=True)
class LengthThresholds:
    """Word-count boundaries for the measured length strata (from configuration)."""

    short_max_words: int = 80
    medium_max_words: int = 600

    def stratum(self, words: int) -> str:
        if words <= self.short_max_words:
            return "short"
        if words <= self.medium_max_words:
            return "medium"
        return "long"


def _digest(*parts: object) -> str:
    return hashlib.sha256("|".join(str(p) for p in parts).encode()).hexdigest()


def generate_prompts(
    count: int,
    seed: int,
    *,
    thresholds: LengthThresholds | None = None,
    templates: list[str] | None = None,
) -> list[PromptRecord]:
    """Generate ``count`` deterministic prompts (identical output for identical inputs)."""
    if count < 1:
        raise ValueError("count must be >= 1")
    thresholds = thresholds or LengthThresholds()
    template_ids = sorted(templates or TEMPLATES)
    unknown = set(template_ids) - set(TEMPLATES)
    if unknown:
        raise ValueError(f"Unknown templates: {sorted(unknown)}")
    prompts: list[PromptRecord] = []
    for index in range(count):
        template_id = template_ids[index % len(template_ids)]
        stratum = TARGET_STRATA[(index // len(template_ids)) % len(TARGET_STRATA)]
        category, builder = TEMPLATES[template_id]
        rng = random.Random(_digest(seed, index, template_id))
        built = builder(rng, stratum)
        system = built.system
        system_variant = "template" if system else "none"
        if system is None and rng.random() < 0.5:
            sentences = 1 if rng.random() < 0.6 else rng.randint(4, 12)
            system = "You are a helpful assistant. " + " ".join(
                sentence(rng) for _ in range(sentences)
            )
            system_variant = "short" if sentences == 1 else "long"
        messages = [PromptMessage(role="system", content=system)] if system else []
        messages += [
            PromptMessage.model_validate({"role": r, "content": t}) for r, t in built.history
        ]
        messages.append(PromptMessage(role="user", content=built.user))
        words = sum(len(m.content.split()) for m in messages)
        measured = thresholds.stratum(words)
        variation_id = f"{stratum.name}-sys_{system_variant}"
        prompts.append(
            PromptRecord.model_validate(
                dict(
                    prompt_id=f"gen_{_digest(seed, index, template_id)[:16]}",
                    prompt_family_id=f"fam_{template_id}_{_digest(built.topic_key)[:10]}",
                    prompt_template_id=template_id,
                    category=category,
                    subcategory=built.subcategory,
                    generation_seed=seed,
                    variation_id=variation_id,
                    messages=messages,
                    tools=[ToolDefinition.model_validate(tool) for tool in built.tools],
                    source=GENERATOR_SOURCE,
                    source_detail=(
                        f"seshat.data.generators templates {TEMPLATE_LIBRARY_VERSION}; "
                        f"seed={seed}; index={index}"
                    ),
                    language="en",
                    complexity=built.difficulty,
                    is_synthetic=True,
                    license_id="project-authored",
                    commercial_use_allowed=True,
                    tags=[
                        f"length_stratum:{measured}",
                        f"target_stratum:{stratum.name}",
                        f"system:{system_variant}",
                    ],
                    review_status="approved",
                    reviewed_by="template-code-review",
                    review_notes=(
                        "Generated by a version-controlled template; "
                        "review happens on the template in code review."
                    ),
                    metadata={
                        "length_stratum": measured,
                        "word_count": words,
                        "template_library_version": TEMPLATE_LIBRARY_VERSION,
                    },
                )
            )
        )
    return merge_near_duplicate_families(prompts)


def merge_near_duplicate_families(
    prompts: list[PromptRecord], threshold: float = NEAR_DUPLICATE_THRESHOLD
) -> list[PromptRecord]:
    """Give near-duplicate prompts one family (union-find, smallest id wins).

    Procedurally generated long documents can converge textually across topics;
    merging their families keeps such twins on the same side of every split.
    """
    from seshat.prompts.dedup import near_duplicate_pairs

    parent = {p.prompt_family_id: p.prompt_family_id for p in prompts}

    def find(item: str) -> str:
        while parent[item] != item:
            parent[item] = parent[parent[item]]
            item = parent[item]
        return item

    family_of = {p.prompt_id: p.prompt_family_id for p in prompts}
    for pair in near_duplicate_pairs(prompts, threshold):
        a, b = find(family_of[pair.prompt_id]), find(family_of[pair.other_id])
        if a != b:
            parent[max(a, b)] = min(a, b)
    return [
        p
        if find(p.prompt_family_id) == p.prompt_family_id
        else p.model_copy(
            update={
                "prompt_family_id": find(p.prompt_family_id),
                "metadata": {**p.metadata, "family_merged_from": p.prompt_family_id},
            }
        )
        for p in prompts
    ]
